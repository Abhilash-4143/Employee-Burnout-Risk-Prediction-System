"""PDF report generation for the Employee Burnout Risk Prediction System.

Produces reports/EDA_Report.pdf and reports/Model_Report.pdf from the text
reports and screenshots generated by main.py. Uses fpdf2.

Run with:  python -m src.report_generator   (after running main.py)
"""

from __future__ import annotations

import os
from typing import List

from fpdf import FPDF

REPORTS_DIR = "reports"
SCREENSHOTS_DIR = "screenshots"


class _PDF(FPDF):
    """PDF with a styled header and footer."""

    title_text = "Employee Burnout Risk Prediction"

    def header(self) -> None:  # noqa: D401
        self.set_font("Helvetica", "B", 12)
        self.cell(0, 10, self.title_text, ln=True, align="C")
        self.ln(2)

    def footer(self) -> None:  # noqa: D401
        self.set_y(-15)
        self.set_font("Helvetica", "I", 8)
        self.cell(0, 10, f"Page {self.page_no()}", align="C")


def _text_block(pdf: _PDF, heading: str, body: str) -> None:
    pdf.set_font("Helvetica", "B", 13)
    pdf.multi_cell(0, 8, heading)
    pdf.set_font("Courier", "", 9)
    for line in body.splitlines():
        pdf.multi_cell(0, 5, line)
    pdf.ln(3)


def _add_images(pdf: _PDF, names: List[str]) -> None:
    for name in names:
        path = os.path.join(SCREENSHOTS_DIR, name)
        if os.path.exists(path):
            pdf.add_page()
            pdf.set_font("Helvetica", "B", 11)
            pdf.multi_cell(0, 8, name.replace("_", " ").replace(".png", "").title())
            pdf.image(path, w=180)


def _read(path: str, fallback: str) -> str:
    if os.path.exists(path):
        with open(path, encoding="utf-8") as fh:
            return fh.read()
    return fallback


def generate_eda_report() -> str:
    """Generate the EDA PDF report."""
    os.makedirs(REPORTS_DIR, exist_ok=True)
    pdf = _PDF()
    pdf.title_text = "EDA Report"
    pdf.add_page()
    _text_block(
        pdf, "Exploratory Data Analysis",
        _read(os.path.join(REPORTS_DIR, "preprocessing_report.txt"),
              "Run main.py to populate this report."),
    )
    _add_images(pdf, [
        "correlation_heatmap.png", "histograms.png", "boxplots.png",
        "scatter_vs_target.png", "target_distribution.png",
        "feature_importance.png",
    ])
    out = os.path.join(REPORTS_DIR, "EDA_Report.pdf")
    pdf.output(out)
    return out


def generate_model_report() -> str:
    """Generate the model evaluation PDF report."""
    os.makedirs(REPORTS_DIR, exist_ok=True)
    pdf = _PDF()
    pdf.title_text = "Model Report"
    pdf.add_page()
    _text_block(
        pdf, "Model Evaluation & Interpretation",
        _read(os.path.join(REPORTS_DIR, "model_report.txt"),
              "Run main.py to populate this report."),
    )
    _add_images(pdf, [
        "actual_vs_predicted.png", "residual_plots.png", "coefficient_plot.png",
    ])
    out = os.path.join(REPORTS_DIR, "Model_Report.pdf")
    pdf.output(out)
    return out


if __name__ == "__main__":
    print(generate_eda_report())
    print(generate_model_report())
